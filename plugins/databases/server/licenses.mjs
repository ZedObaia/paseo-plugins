import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdtemp, readFile, readdir, realpath, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync, gunzipSync } from "node:zlib";

const plugin = path.resolve(import.meta.dirname, "..");
const assets = path.join(plugin, "assets");
const digest = (bytes) => createHash("sha256").update(bytes).digest("hex");
const json = async (file) => JSON.parse(await readFile(file, "utf8"));
const licenseFile = (file) =>
  /^(licen[cs]e|copying|notice|copyright|authors)(?:[._ -]|$)|third.?party.*(?:notice|licen[cs]e)/i.test(
    path.basename(file),
  );
const buildInputs = [
  "server/studio.patch",
  "server/studio-dependencies.patch",
  "server/assistant.tsx.txt",
  "server/studio-vite.config.ts.txt",
  "server/build-studio.mjs",
];
const supplementsFile = path.join(assets, "license-supplements/manifest.json");
const reviews = await json(supplementsFile);
const licenseOverrides = new Map(
  reviews
    .filter((entry) => entry.license)
    .flatMap((entry) => entry.packages.map((name) => [name, entry.license])),
);

async function supplements(name, version) {
  return Promise.all(
    reviews
      .filter((entry) => entry.packages.includes(`${name}@${version}`))
      .map(async (entry) => ({
        file: entry.file,
        source: entry.source,
        text: await readFile(path.join(path.dirname(supplementsFile), entry.file), "utf8"),
      })),
  );
}

export async function packageNotices(directory) {
  const pkg = await json(path.join(directory, "package.json"));
  const notices = [];
  async function visit(at) {
    for (const entry of await readdir(at, { withFileTypes: true })) {
      if (entry.name === "node_modules" || entry.name === ".git") continue;
      const file = path.join(at, entry.name);
      if (entry.isDirectory()) await visit(file);
      else if (entry.isFile() && licenseFile(entry.name)) {
        notices.push({
          file: path.relative(directory, file).split(path.sep).join("/"),
          text: await readFile(file, "utf8"),
        });
      }
    }
  }
  await visit(directory);
  if (!notices.some((notice) => /licen[cs]e|copying/i.test(notice.file))) {
    const readme = await readFile(path.join(directory, "README.md"), "utf8").catch(() => "");
    const section = readme.match(/(?:^|\n)#{1,3} licen[cs]e\s*\r?\n([\s\S]*)/i)?.[1];
    if (section?.includes("Permission is hereby granted"))
      notices.push({ file: "README.md#license", text: section });
  }
  notices.push(...(await supplements(pkg.name, pkg.version)));
  return {
    name: pkg.name,
    version: pkg.version,
    license: licenseOverrides.get(`${pkg.name}@${pkg.version}`) ?? pkg.license,
    author: pkg.author,
    repository: typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url,
    notices,
  };
}

async function packageDirectories(source) {
  const found = new Map();
  const seen = new Set();
  async function modules(at) {
    for (const entry of await readdir(at, { withFileTypes: true }).catch(() => [])) {
      if (entry.name === ".bin" || entry.name === ".cache") continue;
      const location = path.join(at, entry.name);
      if (entry.name === ".bun") {
        for (const bundle of await readdir(location))
          await modules(path.join(location, bundle, "node_modules"));
      } else if (entry.name.startsWith("@")) await modules(location);
      else {
        const directory = await realpath(location).catch(() => null);
        if (!directory || seen.has(directory)) continue;
        seen.add(directory);
        const pkg = await json(path.join(directory, "package.json")).catch(() => null);
        if (!pkg) continue;
        found.set(`${pkg.name}@${pkg.version}`, directory);
        await modules(path.join(directory, "node_modules"));
      }
    }
  }
  await modules(path.join(source, "node_modules"));
  await modules(path.join(source, "packages/web/node_modules"));
  return found;
}

export async function frontendNotices(source, scope) {
  const report = await json(path.join(source, "packages/web/dist/third-party-licenses.json"));
  const directories = await packageDirectories(source);
  // CSS assets are generated by build plugins, so Vite's JavaScript module report omits these.
  for (const name of ["@fontsource-variable/jetbrains-mono", "tailwindcss", "tw-animate-css"]) {
    const pkg = await json(path.join(source, "packages/web/node_modules", name, "package.json"));
    if (!report.some((entry) => entry.name === name && entry.version === pkg.version))
      report.push({ name, version: pkg.version });
  }
  const entries = [];
  for (const item of report) {
    const directory = directories.get(`${item.name}@${item.version}`);
    assert.ok(directory, `Cannot locate bundled package ${item.name}@${item.version}`);
    const entry = await packageNotices(directory);
    if (item.text && !entry.notices.some((notice) => notice.text === item.text))
      entry.notices.push({ file: "Vite license report", text: item.text });
    entries.push({ ...entry, scopes: [scope] });
  }
  return entries;
}

export async function writeFrontendCatalog(entries, revision) {
  for (const entry of await json(supplementsFile)) {
    if (!entry.vendored) continue;
    entries.push({
      ...entry.vendored,
      version: `db-studio@${revision}`,
      kind: "vendored",
      scopes: ["frontend"],
      repository: entry.source,
      notices: [
        {
          file: entry.file,
          source: entry.source,
          text: await readFile(path.join(path.dirname(supplementsFile), entry.file), "utf8"),
        },
      ],
    });
  }
  const inputs = Object.fromEntries(
    await Promise.all(
      buildInputs.map(async (file) => [file, digest(await readFile(path.join(plugin, file)))]),
    ),
  );
  await writeFile(
    path.join(assets, "frontend-licenses.json.gz"),
    gzipSync(JSON.stringify({ revision, inputs, entries }), { level: 9 }),
  );
}

async function backendNotices(lock) {
  const entries = [];
  for (const [location, pkg] of Object.entries(lock.packages)) {
    if (!location || pkg.dev) continue;
    let directory = path.join(plugin, location);
    let temporary;
    try {
      const installed = await json(path.join(directory, "package.json")).catch(() => null);
      if (installed?.version !== pkg.version) {
        temporary = await mkdtemp(path.join(tmpdir(), "paseo-db-license-"));
        assert.ok(pkg.resolved.startsWith("https://"), `No HTTPS archive for ${location}`);
        const response = await fetch(pkg.resolved);
        assert.ok(response.ok, `Cannot fetch ${pkg.resolved}: ${response.status}`);
        const bytes = Buffer.from(await response.arrayBuffer());
        const integrity =
          pkg.integrity.split(/\s+/).find((value) => value.startsWith("sha512-")) ?? pkg.integrity;
        const [algorithm, expected] = integrity.split("-", 2);
        assert.equal(
          createHash(algorithm).update(bytes).digest("base64"),
          expected,
          `Archive integrity mismatch: ${location}`,
        );
        const archive = path.join(temporary, "package.tgz");
        await writeFile(archive, bytes);
        const files = execFileSync("tar", ["-tzf", archive], { encoding: "utf8" })
          .trim()
          .split("\n")
          .filter(
            (file) => licenseFile(file) || file === "package/package.json" || file === "package/README.md",
          );
        assert.ok(
          files.every((file) => file.startsWith("package/") && !file.split("/").includes("..")),
          "Invalid package archive paths",
        );
        execFileSync("tar", ["-xzf", archive, "-C", temporary, "--", ...files]);
        directory = path.join(temporary, "package");
      }
      entries.push({
        ...(await packageNotices(directory)),
        scopes: ["backend"],
        archive: pkg.resolved,
        integrity: pkg.integrity,
      });
    } finally {
      if (temporary) await rm(temporary, { recursive: true, force: true });
    }
  }
  return entries;
}

function mergeEntries(entries) {
  const result = new Map();
  for (const entry of entries) {
    entry.notices = [...new Map(entry.notices.map((notice) => [notice.text, notice])).values()];
    const key = `${entry.name}@${entry.version}`;
    assert.ok(
      typeof entry.license === "string" && !/UNLICENSED|UNKNOWN|SEE LICENSE/i.test(entry.license),
      `Unresolved license: ${key}`,
    );
    assert.ok(
      entry.notices.some(
        (notice) =>
          notice.text.length > 100 &&
          /licen[cs]e|copying|permission|public domain|redistribution/i.test(notice.text),
      ),
      `Missing license text: ${key}`,
    );
    const previous = result.get(key);
    if (!previous) result.set(key, { ...entry, scopes: [...entry.scopes], notices: [...entry.notices] });
    else {
      assert.equal(previous.license, entry.license, `Conflicting licenses: ${key}`);
      previous.scopes = [...new Set([...previous.scopes, ...entry.scopes])].sort();
      for (const notice of entry.notices)
        if (!previous.notices.some((old) => old.text === notice.text)) previous.notices.push(notice);
    }
  }
  return [...result.values()].sort((a, b) =>
    `${a.name}@${a.version}`.localeCompare(`${b.name}@${b.version}`, "en"),
  );
}

async function fingerprints() {
  const files = [
    "package-lock.json",
    "assets/frontend-licenses.json.gz",
    "assets/studio.json.gz",
    "assets/DB-STUDIO-AUTHORS",
    "server/licenses.mjs",
    "assets/license-supplements/manifest.json",
  ];
  const supplements = await json(supplementsFile);
  for (const entry of supplements) files.push(`assets/license-supplements/${entry.file}`);
  return Object.fromEntries(
    await Promise.all(
      [...new Set(files)].map(async (file) => [file, digest(await readFile(path.join(plugin, file)))]),
    ),
  );
}

export async function inventory(check = false) {
  const lock = await json(path.join(plugin, "package-lock.json"));
  const frontend = JSON.parse(
    gunzipSync(await readFile(path.join(assets, "frontend-licenses.json.gz"))).toString(),
  );
  for (const file of buildInputs)
    assert.equal(
      digest(await readFile(path.join(plugin, file))),
      frontend.inputs[file],
      `Rebuild Studio: ${file} changed`,
    );
  const inputs = await fingerprints();
  if (check) {
    const saved = await json(path.join(assets, "THIRD-PARTY-INVENTORY.json"));
    assert.deepEqual(saved.inputs, inputs, "Regenerate the third-party inventory: npm run licenses");
    assert.equal(
      saved.noticesSha256,
      digest(await readFile(path.join(assets, "THIRD-PARTY-NOTICES.txt"))),
      "Third-party notices were modified",
    );
    const runtime = new Set(
      Object.entries(lock.packages)
        .filter(([at, pkg]) => at && !pkg.dev)
        .map(([at, pkg]) => `${at.split("node_modules/").at(-1)}@${pkg.version}`),
    );
    assert.deepEqual(
      new Set(
        saved.packages
          .filter((pkg) => pkg.scopes.includes("backend"))
          .map((pkg) => `${pkg.name}@${pkg.version}`),
      ),
      runtime,
      "Backend license coverage differs from the lockfile",
    );
    assert.deepEqual(
      new Set(
        saved.packages
          .filter((pkg) => pkg.scopes.includes("frontend"))
          .map((pkg) => `${pkg.name}@${pkg.version}`),
      ),
      new Set(frontend.entries.map((pkg) => `${pkg.name}@${pkg.version}`)),
      "Frontend license coverage differs from the built bundle",
    );
    console.log(`Third-party inventory is current: ${saved.packages.length} package versions`);
    return;
  }
  for (const entry of frontend.entries) {
    entry.license = licenseOverrides.get(`${entry.name}@${entry.version}`) ?? entry.license;
    entry.notices.push(...(await supplements(entry.name, entry.version)));
  }
  const packages = mergeEntries([...(await backendNotices(lock)), ...frontend.entries]);
  const notices =
    "THIRD-PARTY NOTICES\n\nGenerated by npm run licenses. Package-provided license and attribution texts follow.\n\n" +
    packages
      .map(
        (entry) =>
          `${"=".repeat(80)}\n${entry.name}@${entry.version}\nLicense: ${entry.license}\nScopes: ${entry.scopes.join(", ")}\n${entry.repository ?? entry.archive ?? ""}\n\n` +
          entry.notices
            .map(
              (notice) =>
                `--- ${notice.file}${notice.source ? ` (${notice.source})` : ""} ---\n${notice.text}`,
            )
            .join("\n\n"),
      )
      .join("\n\n");
  await writeFile(path.join(assets, "THIRD-PARTY-NOTICES.txt"), notices);
  await writeFile(
    path.join(assets, "THIRD-PARTY-INVENTORY.json"),
    JSON.stringify(
      {
        schemaVersion: 1,
        upstreamRevision: frontend.revision,
        inputs,
        noticesSha256: digest(notices),
        packages: packages.map(({ notices: texts, ...entry }) => ({
          ...entry,
          notices: texts.map(({ text, ...notice }) => ({ ...notice, sha256: digest(text) })),
        })),
      },
      null,
      2,
    ) + "\n",
  );
  console.log(`Wrote third-party notices for ${packages.length} package versions`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  await inventory(process.argv.includes("--check"));
